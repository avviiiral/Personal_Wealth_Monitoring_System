import json

from django.core.management.base import BaseCommand
from django.db import transaction

from market_data.services.security_resolver import SecurityResolver
from market_data.services.security_resolver_diagnostics import (
    STATUS_MATCHED,
    STATUS_ORDER,
    diagnostic_assets,
    run_diagnostics,
    summarize,
)


class Command(BaseCommand):
    help = (
        "Read-only report of how STOCK/ETF/legacy Direct Equity assets "
        "resolve to Yahoo symbols through SecurityResolver and the Security "
        "Master. Writes nothing: no Asset, MarketPrice or workbook changes, "
        "no workbook auto-generation and no network calls."
    )

    def add_arguments(self, parser):
        parser.add_argument(
            "--asset-id",
            type=int,
            action="append",
            dest="asset_ids",
            help="Diagnose this asset id (repeatable). Bypasses the default scope.",
        )
        parser.add_argument(
            "--isin",
            action="append",
            dest="isins",
            help="Diagnose assets with this ISIN (repeatable). Bypasses the default scope.",
        )
        parser.add_argument(
            "--user-id",
            type=int,
            help="Only assets owned by this user (same filter as update_market_prices).",
        )
        parser.add_argument(
            "--only-issues",
            action="store_true",
            help=f"Hide {STATUS_MATCHED} rows that have no notes.",
        )
        parser.add_argument(
            "--format",
            choices=("table", "json"),
            default="table",
            help="Output format (default: table).",
        )

    def handle(self, *args, **options):
        # Load the workbook fresh, but never generate it: a missing workbook
        # is reported as such instead of being created by the diagnostic.
        SecurityResolver.reload_security_master(generate_if_missing=False)
        workbook_path = SecurityResolver._security_master_path()

        # Defence in depth: the diagnostic only reads, and any accidental
        # write would be rolled back.
        with transaction.atomic():
            assets = diagnostic_assets(
                user_id=options.get("user_id"),
                asset_ids=options.get("asset_ids"),
                isins=options.get("isins"),
            )
            rows, workbook_error = run_diagnostics(assets, workbook_path=workbook_path)
            transaction.set_rollback(True)

        counts = summarize(rows)
        shown = [
            row for row in rows
            if not options["only_issues"] or row.status != STATUS_MATCHED or row.reason
        ]

        if options["format"] == "json":
            self.stdout.write(json.dumps(
                {
                    "security_master": str(workbook_path) if workbook_path else None,
                    "security_master_error": workbook_error,
                    "assets_checked": len(rows),
                    "summary": counts,
                    "rows": [row.as_dict() for row in shown],
                },
                indent=2,
            ))
            return

        self._write_table(shown, workbook_path, workbook_error, len(rows), counts)

    def _write_table(self, rows, workbook_path, workbook_error, total, counts):
        if workbook_path and workbook_error:
            self.stdout.write(self.style.ERROR(
                f"Security Master: {workbook_path} could not be read ({workbook_error}). "
                "The resolver falls back to built-in mappings, so the statuses below "
                "reflect that fallback."
            ))
        elif workbook_path:
            self.stdout.write(f"Security Master: {workbook_path}")
        else:
            self.stdout.write(self.style.WARNING(
                "Security Master: not found (not generated by this diagnostic; "
                "only built-in mappings were used)."
            ))
        self.stdout.write(f"Assets checked: {total}")
        self.stdout.write("")

        headers = ("ID", "Asset", "ISIN", "DB Symbol", "SM Symbol", "Resolved", "Status", "Reason")
        table = [
            (
                str(row.asset_id),
                row.asset_name if len(row.asset_name) <= 40 else row.asset_name[:39] + "~",
                row.isin or "-",
                row.database_symbol or "-",
                row.security_master_symbol or "-",
                row.resolved_symbol or "-",
                row.status,
                row.reason or "-",
            )
            for row in rows
        ]
        widths = [
            max([len(headers[index])] + [len(line[index]) for line in table])
            for index in range(len(headers) - 1)
        ]

        def format_line(values):
            fixed = "  ".join(
                value.ljust(widths[index]) for index, value in enumerate(values[:-1])
            )
            return f"{fixed}  {values[-1]}"

        self.stdout.write(format_line(headers))
        self.stdout.write(format_line(tuple("-" * width for width in widths) + ("-" * 6,)))
        for line in table:
            text = format_line(line)
            status = line[6]
            if status == STATUS_MATCHED:
                self.stdout.write(text)
            elif status in ("NOT_IN_MASTER", "MISSING_ISIN"):
                self.stdout.write(self.style.WARNING(text))
            else:
                self.stdout.write(self.style.ERROR(text))

        self.stdout.write("")
        self.stdout.write("Summary: " + ", ".join(
            f"{status}={counts.get(status, 0)}" for status in STATUS_ORDER
        ))
